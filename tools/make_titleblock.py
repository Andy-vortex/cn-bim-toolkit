"""生成约定包的图框和视图标题模板：python tools/make_titleblock.py（写进 JZ_DRAWING_PACK 指的约定包，不设时是 packs/cn/drawing）

写出三个文件（名字不和 Bonsai 自带的模板重名）：
  titleblocks/A3-CN.svg        平面类图纸的 A3 横式图框（左侧装订边，右侧竖向标题栏）
  titleblocks/A3-CN-TABLE.svg  表格类图纸（图纸目录、门窗表）的图框：和 A3-CN 完全相同，只是不画指北针
  view-title-CN.svg            视图标题：图名（大号字）、比例（小号字）同一基线，图名下一条粗实线（长度出图时按图名改写）
标题栏自上而下：设计单位和签章区（留白）、工程名称、设计/校对/审核（每行实名、签名两格）、比例、日期、附注一句、
指北针（GB/T 50001：直径 24mm 细实线圆，指针尾宽 3mm，头部注 N）、图名、图号（右下角）。字号只有两档。
幅面、装订边和留边、标题栏宽、两档字号、视图标题图名和比例的间隔读约定包 conventions.json 的 titleblock 一节
（drawset 出图时折行、定可放图区域读的是同一份）。
字段用 Bonsai 的 mustache 模板，值取图纸的 IfcDocumentInformation（对应关系见 drawset.SHEET_FIELDS）：
  {{Description}} 工程名称 / {{Name}} 图名 / {{Identification}} 图号 / {{Purpose}} 比例 / {{IntendedUse}} 日期
工程名称、图名两格的值带 class tb-proj、tb-title，出图时 drawset 按格宽折行（不缩字）。
模板纯 ASCII，中文写成 XML 数字字符引用：Bonsai 读模板时不指定编码，GBK、UTF-8 的机器都不会乱码。
线宽参照 GB/T 50001-2017（A3 取 b=0.7：图框线 b，标题栏外框和图名一栏的上边 0.7b，分格线 0.35b），待复核。
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src"))
from jiazhuang import conventions, printing  # noqa: E402

_p = argparse.ArgumentParser(prog="python tools/make_titleblock.py", allow_abbrev=False,
                             description="按约定包 conventions.json 的 titleblock 重新生成约定包里的图框和视图标题模板"
                                         "（约定包：环境变量 JZ_DRAWING_PACK，不设时是 packs/cn/drawing）。")
_p.parse_args()
if err := conventions.check_pack(("conventions.json",)):   # 模板是这里生成的，只要 conventions.json
    _p.error(err)
OUT_DIR = conventions.pack_dir()
TB = conventions.get("titleblock")


def ent(s: str) -> str:
    return "".join(c if ord(c) < 128 else f"&#{ord(c)};" for c in s)


FONT = "FangSong,'STFangsong','Noto Serif CJK SC',serif"
NOTE = ("方案图，须专业复核", "及现场复尺后施工")   # 附注：一句，折两行
SMALL, BIG = TB["small_mm"], TB["big_mm"]          # 两档字号（mm）

W, H = TB["sheet_mm"]
M = TB["margin_mm"]
FX0, FY0, FX1, FY1 = TB["binding_mm"], M, W - M, H - M   # 图框：左侧装订边，其余留边
TX0 = FX1 - TB["width_mm"]                         # 标题栏左边
CX = TX0 + TB["width_mm"] // 2                     # 标题栏中线（尺寸都是整数毫米）
LAB = TX0 + 9                                      # 标签列右边
LCX = (TX0 + LAB) / 2                              # 标签列中线（设计、校对、审核、比例、日期、图号居中写在这里）
VCX = (LAB + FX1) / 2                              # 标签右侧那格的中线；签字行里也是实名、签名两格的分界
FRAME, OUTER, GRID = 0.7, 0.5, 0.25
# 各栏的上边（y，mm）
Y_PROJ, Y_SIGN, Y_SCALE, Y_DATE, Y_NOTE, Y_TITLE, Y_ID = 142, 170, 194, 201, 208, 256, 280
NORTH_C, NORTH_R = 240, 12                          # 指北针圆心 y、半径


def base(top, bottom, size):
    """在 [top, bottom] 里上下居中的一行字的基线（汉字字面中心约在基线上 0.35 字号处）。"""
    return round((top + bottom) / 2 + 0.35 * size, 2)


def titleblock(table: bool) -> str:
    out = []
    a = out.append
    a('<?xml version="1.0" encoding="UTF-8" standalone="no"?>')
    a("<!-- generated by tools/make_titleblock.py; MIT, see LICENSE -->")
    a(f'<svg xmlns="http://www.w3.org/2000/svg" id="root" version="1.1" width="{W}mm" height="{H}mm" viewBox="0 0 {W} {H}">')
    # 只用本模板自己的类名，不写 text{} 这种会波及整张图纸的选择器
    a(f"<style>.tb-s{{font-family:{FONT};font-size:{SMALL}px;fill:#000;stroke:none}}"
      f".tb-l{{font-family:{FONT};font-size:{BIG}px;fill:#000;stroke:none}}.tb-b{{font-weight:bold}}</style>")
    a(f'<rect x="0" y="0" width="{W}" height="{H}" fill="#fff" stroke="none"/>')
    a(f'<rect x="{FX0}" y="{FY0}" width="{FX1 - FX0}" height="{FY1 - FY0}" fill="none" stroke="#000" stroke-width="{FRAME}"/>')
    a(f'<rect x="{TX0}" y="{FY0}" width="{FX1 - TX0}" height="{FY1 - FY0}" fill="none" stroke="#000" stroke-width="{OUTER}"/>')

    def hline(y, w=GRID):
        a(f'<line x1="{TX0}" y1="{y}" x2="{FX1}" y2="{y}" stroke="#000" stroke-width="{w}"/>')

    def vline(x, y0, y1):
        a(f'<line x1="{x}" y1="{y0}" x2="{x}" y2="{y1}" stroke="#000" stroke-width="{GRID}"/>')

    def text(x, y, s, cls, anchor="start"):
        a(f'<text x="{x}" y="{y}" class="{cls}" text-anchor="{anchor}">{s}</text>')

    # 1. 设计单位和签章区：留白
    # 2. 工程名称：标签在上，值用小号字（tb-proj，出图时折行）
    hline(Y_PROJ)
    text(TX0 + 2, round(Y_PROJ + 1.5 + 0.88 * SMALL, 2), ent("工程名称"), "tb-s")
    text(CX, base(Y_PROJ + 6.5, Y_SIGN, SMALL), "{{Description}}", "tb-s tb-proj", "middle")
    # 3. 设计、校对、审核：标签 | 实名 | 签名（不加表头）；标签在标签列里居中，两边留白相等
    for i, s in enumerate(("设计", "校对", "审核")):
        y = Y_SIGN + 8 * i
        hline(y)
        text(LCX, base(y, y + 8, SMALL), ent(s), "tb-s", "middle")
    vline(VCX, Y_SIGN, Y_SCALE)
    # 4. 比例、日期：标签 | 值
    for y0, y1, s, tpl in ((Y_SCALE, Y_DATE, "比例", "{{Purpose}}"), (Y_DATE, Y_NOTE, "日期", "{{IntendedUse}}")):
        hline(y0)
        text(LCX, base(y0, y1, SMALL), ent(s), "tb-s", "middle")
        text(VCX, base(y0, y1, SMALL), tpl, "tb-s", "middle")
    vline(LAB, Y_SIGN, Y_NOTE)
    hline(Y_NOTE)
    # 5. 附注：一句，小号字，折两行
    for i, s in enumerate(NOTE):
        text(TX0 + 2, base(Y_NOTE + 1 + 5 * i, Y_NOTE + 6 + 5 * i, SMALL), ent(s), "tb-s")
    # 6. 指北针（Bonsai 按项目网格北旋转 data-type="grid-north" 组）；表格图框不画，其余位置完全相同
    if not table:
        r = NORTH_R
        a(f'<g transform="translate({CX},{NORTH_C})"><g data-type="grid-north">'
          f'<circle cx="0" cy="0" r="{r}" fill="none" stroke="#000" stroke-width="{GRID}"/>'
          f'<path d="M 0,{-r} L 1.5,{r} L -1.5,{r} Z" fill="#000" stroke="none"/>'
          f'<text x="0" y="{-r - 1.2}" class="tb-l" text-anchor="middle">N</text></g></g>')
    # 7. 图名：标签在上，值用大号字（tb-title，出图时折行）
    hline(Y_TITLE, OUTER)
    text(TX0 + 2, round(Y_TITLE + 1.5 + 0.88 * SMALL, 2), ent("图名"), "tb-s")
    text(CX, base(Y_TITLE + 6, Y_ID, BIG), "{{Name}}", "tb-l tb-title", "middle")
    # 8. 图号：落在整张图的右下角，大号字加粗
    hline(Y_ID)
    text(LCX, base(Y_ID, FY1, SMALL), ent("图号"), "tb-s", "middle")
    text(VCX, base(Y_ID, FY1, BIG), "{{Identification}}", "tb-l tb-b", "middle")
    vline(LAB, Y_ID, FY1)
    a("</svg>")
    return "\n".join(out) + "\n"


def view_title() -> str:
    """视图标题（Bonsai 排图纸时读 <LayoutsDir>/assets/view-title.svg，图名、比例两个占位由 Bonsai 填）：
    没有 Bonsai 自带的编号圈；宽度只是裁切框，留足长图名。粗线长度由 drawset 按图名估宽改写。"""
    return "\n".join([
        '<?xml version="1.0" encoding="UTF-8" standalone="no"?>',
        "<!-- generated by tools/make_titleblock.py; MIT, see LICENSE -->",
        '<svg xmlns="http://www.w3.org/2000/svg" version="1.1" width="200mm" height="9mm" viewBox="0 0 200 9">',
        f'<text x="0" y="6" style="font-family:{FONT};fill:#000;stroke:none">'
        f'<tspan style="font-size:{BIG}px">{{{{Name}}}}</tspan><tspan dx="{TB["view_title_gap_mm"]}" style="font-size:{SMALL}px">'
        f'{{{{Scale}}}}</tspan></text>',
        '<path data-jz="vt-line" d="M 0,7.4 H 40" style="fill:none;stroke:#000;stroke-width:0.5"/>',
        "</svg>"]) + "\n"


for rel, body in (("titleblocks/A3-CN.svg", titleblock(False)), ("titleblocks/A3-CN-TABLE.svg", titleblock(True)),
                  ("view-title-CN.svg", view_title())):
    p = os.path.join(OUT_DIR, *rel.split("/"))
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w", encoding="ascii", newline="\n") as fh:
        fh.write(body)
    printing.log("wrote", p)
printing.done(OUT_DIR)
